import type { ToolDefinition } from '../../data/tools';

export function HelpContent({ tool }: { tool?: ToolDefinition }) {
  return (
    <>
      <p className="dialog-intro">この案内を閉じると、そのまま作業を続けられます。</p>
      {tool && (
        <section className="help-current-tool" aria-labelledby="help-current-tool">
          <h3 id="help-current-tool">使用中：{tool.japaneseName}</h3>
          <p>{tool.description}</p>
          <p>詳しい設定は、作業画面下部の「使い方のヒント」で確認できます。</p>
        </section>
      )}
      <h3>基本の使い方</h3>
      <ol>
        <li>ツールを開いて、テキスト・ファイルを入力するか、設定を調整します。</li>
        <li>
          プレビューを確認します。実行ボタンがあるツールは「生成」「変換」などを押してください。
        </li>
        <li>結果の「コピー」または「保存」で取り出します。</li>
      </ol>
      <p>
        初めて使うときは「サンプル」で試せます。「サンプル」「リセット」の直後は「元に戻す」で直前の入力・設定・結果を1回戻せます。次の編集、実行・コピー・保存などの操作や別のツールへの移動で、取り消し履歴は消えます。読み込み途中の処理は再開しません。
      </p>
      <p>
        スマートフォンやタブレットでは「入力・設定へ」「結果へ」で作業エリアを移動できます。入力内容や取り消し履歴はそのまま保持されます。
      </p>
      <h3>コピー・保存ができないとき</h3>
      <p>
        まず結果が表示されているか、入力エラーがないか確認してください。ブラウザがコピーを許可しない場合は、結果のテキストを選択してコピーするか、ファイル保存を利用できます。保存先はブラウザのダウンロード設定に従います。
      </p>
      <h3>ファイルを読み込めないとき</h3>
      <p>
        読み込み欄の対応形式・容量上限と、表示されたエラーを確認してください。ファイル名の拡張子を変えるだけでは形式は変換されません。
      </p>
      <h3>入力内容と画面の移動</h3>
      <p>
        処理はブラウザ内で行い、入力した画像・テキストを外部に送信しません。入力は保存されず、別のツールへ移動したり再読み込みしたりすると消えます。Help・更新情報を開く操作や、ライト／ダーク切り替えでは入力は消えません。
      </p>
      <h3>オフライン・テーマ・キーボード</h3>
      <p>
        オフライン利用には初回のオンラインでの準備が必要です。準備状況は右上の「更新情報」で確認できます。ライト／ダークの切り替えは画面の表示にだけ適用され、生成する画像やCSSの色は変わりません。
      </p>
      <p>
        Tabで次の操作、Shift+Tabで前の操作へ移動できます。この案内はEscキー、または「閉じる」で閉じられます。
      </p>
    </>
  );
}
