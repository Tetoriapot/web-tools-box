export function filterTools(query: string, category: string = 'all') {
  const terms = query.normalize('NFKC').toLocaleLowerCase().trim().split(/\s+/u).filter(Boolean);
  return tools.filter((tool) => {
    const haystack = [tool.name, tool.japaneseName, tool.description, ...tool.keywords]
      .join(' ')
      .normalize('NFKC')
      .toLocaleLowerCase();
    return (
      (category === 'all' || tool.category === category) &&
      terms.every((term) => haystack.includes(term))
    );
  });
}
